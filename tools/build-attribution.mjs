#!/usr/bin/env node
/**
 * build-attribution.mjs — generates docs/GAMES_ATTRIBUTION.md from the
 * committed catalog + its sources config.
 *
 * Nothing is bundled with Playhub: every entry below is downloaded ON DEMAND
 * from its original host when the user clicks Install. This file records what
 * the catalog points at, who made it, and under what license terms.
 *
 * Usage: node tools/build-attribution.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'catalog', 'catalog.json'), 'utf8'));
const config = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'catalog-sources.json'), 'utf8'));

const lines = [];
lines.push('# Games Attribution', '');
lines.push(`HTML Playhub ships with **no preinstalled games**. Its Discover catalog points at **${catalog.games.length} games** from **${catalog.sources.length} sources**, downloaded on demand from the original hosts when the user clicks Install (pinned URLs, verified by CI).`, '');
lines.push('The launcher itself is MIT licensed (see LICENSE). Each game below keeps its own license and copyright. Entries marked **Unknown** have no license stated by the author: Playhub downloads them from the original host for your personal use — redistribution rights are unknown, so do not re-share those files.', '');

for (const s of catalog.sources) {
  const entries = catalog.games.filter((g) => g.sourceCollection === s.collection)
    .sort((a, b) => String(a.title).localeCompare(String(b.title)));
  const repoLink = Array.isArray(s.repo)
    ? s.repo.map((r) => `[repo](${r.replace(/\.git$/, '')})`).join(' · ')
    : (s.repo ? `[repo](${s.repo.replace(/\.git$/, '')})` : `[site](${s.homepage})`);
  lines.push(`## ${s.collection} — ${entries.length} game(s), ${s.license} — ${repoLink}`, '');
  lines.push('| Game | Author | License | Notes |');
  lines.push('|---|---|---|---|');
  for (const g of entries) {
    const link = g.homepage ? `[${g.title}](${g.homepage})` : g.title;
    const notes = [
      g.offline === false ? 'needs internet' : null,
      g.hasTrackers ? 'contains trackers (auto-sandboxed on install)' : null,
      g.assets ? `+${g.assets.length} asset(s)` : null,
      g.licenseNote ? g.licenseNote : null,
    ].filter(Boolean).join('; ');
    lines.push(`| ${link} | ${g.author} | ${g.license} | ${notes} |`);
  }
  lines.push('');
}

const direct = (config.direct || []).length;
const viaRepos = catalog.games.length - direct;
lines.push(`Generated by \`node tools/build-attribution.mjs\` from catalog v1 (${catalog.updatedAt}): ${viaRepos} entries from pinned repo URLs, ${direct} direct-site entries.`);
lines.push('');

fs.writeFileSync(path.join(ROOT, 'docs', 'GAMES_ATTRIBUTION.md'), lines.join('\n'));
console.log(`attribution: ${catalog.games.length} games, ${catalog.sources.length} sources`);
