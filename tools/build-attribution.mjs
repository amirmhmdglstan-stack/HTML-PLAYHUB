#!/usr/bin/env node
/**
 * build-attribution.mjs — generates docs/GAMES_ATTRIBUTION.md from the catalog.
 * Usage: node tools/build-attribution.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, 'catalog', 'catalog.json'), 'utf8'));

const bundled = catalog.games.filter((g) => g.kind === 'file');
const external = catalog.games.filter((g) => g.kind === 'external');
const bundle = JSON.parse(fs.readFileSync(path.join(ROOT, 'bundled-games', 'bundle.json'), 'utf8'));
const inBundle = new Set(bundle.games.map((g) => g.id));
const shipped = bundled.filter((g) => inBundle.has(g.id));
const downloadable = bundled.filter((g) => !inBundle.has(g.id));

let md = `# Games & Attribution

> Generated by \`node tools/build-attribution.mjs\` — do not edit by hand.
> Catalog updated: ${catalog.updatedAt || 'unknown'}

HTML Playhub ships with **${shipped.length} bundled games** from **${catalog.sources.length} sources**
(installed automatically on first launch, fully offline).
${downloadable.length ? `Another **${downloadable.length}** MIT-licensed games are one click away in Discover (download on demand).` : ''}
Every bundled game was checked for a redistribution-friendly license, keeps its
original files verbatim, and records its author, source and license in its
manifest (visible on each game's page in the app).

An additional **${external.length} entries** are listed in Discover as
*external sources*: they are not bundled (usually for license reasons) and the
app only links to their official sources with import instructions.

## Bundled sources

| Collection | License | Games | Source |
|---|---|---|---|
`;
for (const s of catalog.sources) {
  md += `| ${s.collection} | ${s.license} | ${s.count} | ${s.homepage || s.repo || ''} |\n`;
}

md += `\n## Bundled games\n\n| Game | Author | License | Collection | Offline |\n|---|---|---|---|---|\n`;
for (const g of [...bundled].sort((a, b) => String(a.title).localeCompare(String(b.title)))) {
  md += `| ${g.title} | ${g.author || 'Unknown'} | ${g.license} | ${g.sourceCollection || ''} | ${g.offline === false ? 'needs net' : 'yes'} |\n`;
}

md += `\n## External sources (not bundled)\n\n| Entry | Author | License | Why external |\n|---|---|---|---|\n`;
for (const g of external) {
  md += `| [${g.title}](${g.homepage}) | ${g.author || 'Unknown'} | ${g.license} | ${(g.whyExternal || '').split('.')[0]}. |\n`;
}

md += `\n## License notes

- **MIT / ISC / BSD / Apache-2.0** games: bundled with copyright + permission
  notice (per-collection \`*-LICENSE.txt\` in \`bundled-games/\`, referenced from
  each manifest).
- **GPL-3.0** games (Reversi, Backgammon): bundled as separate, unmodified
  programs with their full license text — mere aggregation with the MIT-licensed
  launcher, which is not a derivative work of the games.
- **Unknown / no license**: never bundled. Discover explains how to obtain and
  import a personal copy.
- If you are a rights holder and want an entry changed or removed, please open
  an issue on the repository.
`;

fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs', 'GAMES_ATTRIBUTION.md'), md);
console.log(`wrote docs/GAMES_ATTRIBUTION.md (${bundled.length} bundled, ${external.length} external)`);
